    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {

            Camionero obj = leerFormulario();
 
            dao.insertar(obj);
            JOptionPane.showMessageDialog(this, "Datos almacenados correctamente");
            limpiar();
            cargarTabla();
        } catch (IllegalArgumentException exp) {
            JOptionPane.showMessageDialog(this, exp.getMessage(), "Validacion", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idCamionero == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un camionero de la tabla");
            return;
        }
        try {
            Camionero obj = leerFormulario();
            obj.setIdCamionero(idCamionero);
            dao.actualizar(obj);
            JOptionPane.showMessageDialog(this, "Datos actualizados correctamente");
            limpiar();
            cargarTabla();
        } catch (IllegalArgumentException exp) {
            JOptionPane.showMessageDialog(this, exp.getMessage(), "Validacion", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idCamionero == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un camionero de la tabla");
            return;
        }
        int resp = JOptionPane.showConfirmDialog(this, "Desea eliminar el registro seleccionado?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (resp != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            dao.eliminar(idCamionero);
            JOptionPane.showMessageDialog(this, "Registro eliminado correctamente");
            limpiar();
            cargarTabla();
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblCamioneroMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCamioneroMouseClicked
        int fila = tblCamionero.getSelectedRow();
        if (fila < 0) {
            return;
        }
        Camionero c = lista.get(fila);
        idCamionero = c.getIdCamionero();
        txtId.setText(String.valueOf(idCamionero));
        txtNombre.setText(c.getNombre());
        txtTelefono.setText(c.getTelefono());
        txtDireccion.setText(c.getDireccion());
        txtSalario.setText(c.getSalario().toString());
        txtPoblacion.setText(c.getPoblacion());
    }//GEN-LAST:event_tblCamioneroMouseClicked

    //limpia las cajas de texto
    private void limpiar() {
        idCamionero = 0;
        txtId.setText("");
        txtNombre.setText("");
        txtTelefono.setText("");
        txtDireccion.setText("");
        txtSalario.setText("");
        txtPoblacion.setText("");
        tblCamionero.clearSelection();
    }

    //crea un objeto a partir de las cajas de texto
    private Camionero leerFormulario() {
        Camionero c = new Camionero();
        c.setNombre(Validar.soloLetras(txtNombre.getText(), "Nombre", 50));
        c.setTelefono(Validar.digitos(txtTelefono.getText(), "Telefono", 8));
        c.setDireccion(Validar.texto(txtDireccion.getText(), "Direccion", 100));
        c.setSalario(Validar.decimalPositivo(txtSalario.getText(), "Salario"));
        c.setPoblacion(Validar.texto(txtPoblacion.getText(), "Poblacion", 50));
        return c;
    }

    //llena la tabla
    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblCamionero.getModel();
        modelo.setRowCount(0);
        try {
            lista = dao.listar();
            for (Camionero x : lista) {
                modelo.addRow(new Object[]{x.getIdCamionero(), x.getNombre(), x.getTelefono(), x.getDireccion(), x.getSalario(), x.getPoblacion()});
            }
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

