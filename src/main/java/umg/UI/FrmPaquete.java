    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            Paquete obj = leerFormulario();
 
            dao.insertar(obj);
            JOptionPane.showMessageDialog(this, "Datos almacenados correctamente");
            limpiar();
            cargarTabla();
        } catch (IllegalArgumentException exp) {
            JOptionPane.showMessageDialog(this, exp.getMessage(), "Validacion", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idPaquete == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un paquete de la tabla");
            return;
        }
        try {
            Paquete obj = leerFormulario();
            obj.setIdPaquete(idPaquete);
            dao.actualizar(obj);
            JOptionPane.showMessageDialog(this, "Datos actualizados correctamente");
            limpiar();
            cargarTabla();
        } catch (IllegalArgumentException exp) {
            JOptionPane.showMessageDialog(this, exp.getMessage(), "Validacion", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idPaquete == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un paquete de la tabla");
            return;
        }
        int resp = JOptionPane.showConfirmDialog(this, "Desea eliminar el registro seleccionado?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (resp != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            dao.eliminar(idPaquete);
            JOptionPane.showMessageDialog(this, "Registro eliminado correctamente");
            limpiar();
            cargarTabla();
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblPaqueteMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPaqueteMouseClicked
        int fila = tblPaquete.getSelectedRow();
        if (fila < 0) {
            return;
        }
        Paquete p = lista.get(fila);
        idPaquete = p.getIdPaquete();
        txtId.setText(String.valueOf(idPaquete));
        txtDescripcion.setText(p.getDescripcion());
        txtDestinatario.setText(p.getDestinatario());
        txtDireccionEnvio.setText(p.getDireccionEnvio());
        for (int i = 0; i < cmbCamionero.getItemCount(); i++) {
            if (cmbCamionero.getItemAt(i).getIdCamionero() == p.getCamionero().getIdCamionero()) {
                cmbCamionero.setSelectedIndex(i);
                break;
            }
        }
        for (int i = 0; i < cmbCiudad.getItemCount(); i++) {
            if (cmbCiudad.getItemAt(i).getIdCiudad() == p.getCiudad().getIdCiudad()) {
                cmbCiudad.setSelectedIndex(i);
                break;
            }
        }
    }//GEN-LAST:event_tblPaqueteMouseClicked

    //limpia las cajas de texto
    private void limpiar() {
        idPaquete = 0;
        txtId.setText("");
        txtDescripcion.setText("");
        txtDestinatario.setText("");
        txtDireccionEnvio.setText("");
        cmbCamionero.setSelectedIndex(-1);
        cmbCiudad.setSelectedIndex(-1);
        tblPaquete.clearSelection();
    }

  
    private Paquete leerFormulario() {
        Paquete p = new Paquete();
        p.setDescripcion(Validar.texto(txtDescripcion.getText(), "Descripcion", 100));
        p.setDestinatario(Validar.soloLetras(txtDestinatario.getText(), "Destinatario", 100));
        p.setDireccionEnvio(Validar.texto(txtDireccionEnvio.getText(), "Direccion de envio", 100));
        Validar.seleccion(cmbCamionero.getSelectedItem(), "un camionero");
        Validar.seleccion(cmbCiudad.getSelectedItem(), "una ciudad de destino");
        p.setCamionero((Camionero) cmbCamionero.getSelectedItem());
        p.setCiudad((Ciudad) cmbCiudad.getSelectedItem());
        return p;
    }

 
    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblPaquete.getModel();
        modelo.setRowCount(0);
        try {
            lista = dao.listar();
            for (Paquete x : lista) {
                modelo.addRow(new Object[]{x.getIdPaquete(), x.getDescripcion(), x.getDestinatario(), x.getDireccionEnvio(), x.getCamionero().toString(), x.getCiudad().getNombre()});
            }
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    //llena los combos con los camioneros y ciudades
    private void cargarCombos() {
        try {
            cmbCamionero.removeAllItems();
            for (Camionero c : new CamioneroDAO().listar()) {
                cmbCamionero.addItem(c);
            }
            cmbCiudad.removeAllItems();
            for (Ciudad c : new CiudadDAO().listar()) {
                cmbCiudad.addItem(c);
            }
            cmbCamionero.setSelectedIndex(-1);
            cmbCiudad.setSelectedIndex(-1);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

