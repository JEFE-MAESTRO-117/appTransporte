    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            //crear objeto de la clase ciudad
            Ciudad ciudad=new Ciudad();
            //validar y capturar los datos de la caja de texto
            ciudad.setNombre(Validar.soloLetras(txtNombre.getText(), "Nombre", 60));
            //crear el objeto dao para almacenar los datos a partir de la clase ciudad
            CiudadDAO dao=new CiudadDAO();
            //almacenar los datos
            dao.insertar(ciudad);
            JOptionPane.showMessageDialog(this, "Datos almacenados correctamente");
            limpiar();
            cargarTabla();
        } catch (IllegalArgumentException exp) {
            JOptionPane.showMessageDialog(this, exp.getMessage(), "Validacion", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException exp){
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if(idCiudad==0){
            JOptionPane.showMessageDialog(this, "Por favor seleccione una ciudad de la tabla");
            return;
        }
        try{
            Ciudad ciudad=new Ciudad();
            //capturar datos de la caja de texto
            ciudad.setIdCiudad(idCiudad);
            ciudad.setNombre(Validar.soloLetras(txtNombre.getText(), "Nombre", 60));
            //crear dao
            CiudadDAO daoac=new CiudadDAO();
            daoac.actualizar(ciudad);
            JOptionPane.showMessageDialog(this, "Datos actualizados correctamente");
            limpiar();
            cargarTabla();
        } catch (IllegalArgumentException exp) {
            JOptionPane.showMessageDialog(this, exp.getMessage(), "Validacion", JOptionPane.WARNING_MESSAGE);
        } catch(SQLException exp){
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if(idCiudad==0){
            JOptionPane.showMessageDialog(this, "Por favor seleccione una ciudad de la tabla");
            return;
        }
        int resp = JOptionPane.showConfirmDialog(this, "Desea eliminar el registro seleccionado?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (resp != JOptionPane.YES_OPTION) {
            return;
        }
        try{
            CiudadDAO daoel=new CiudadDAO();
            daoel.eliminar(idCiudad);
            JOptionPane.showMessageDialog(this, "Registro eliminado correctamente");
            limpiar();
            cargarTabla();
        } catch(SQLException exp){
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblCiudadMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCiudadMouseClicked
        int fila = tblCiudad.getSelectedRow();
        if (fila < 0) {
            return;
        }
        DefaultTableModel modelo = (DefaultTableModel) tblCiudad.getModel();
        idCiudad = (int) modelo.getValueAt(fila, 0);
        txtId.setText(String.valueOf(idCiudad));
        txtNombre.setText(String.valueOf(modelo.getValueAt(fila, 1)));
    }//GEN-LAST:event_tblCiudadMouseClicked

    //llena la tabla con los datos de la base de datos
    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblCiudad.getModel();
        modelo.setRowCount(0);
        try {
            CiudadDAO dao = new CiudadDAO();
            List<Ciudad> lista = dao.listar();
            for (Ciudad c : lista) {
                modelo.addRow(new Object[]{c.getIdCiudad(), c.getNombre()});
            }
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    //limpia las cajas de texto y la seleccion
    private void limpiar() {
        idCiudad = 0;
        txtId.setText("");
        txtNombre.setText("");
        tblCiudad.clearSelection();
    }

