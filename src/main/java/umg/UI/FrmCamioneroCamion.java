    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            CamioneroCamion obj = leerFormulario();
            dao.insertar(obj);
            JOptionPane.showMessageDialog(this, "Datos almacenados correctamente");
            limpiar();
            cargarTabla();
        } catch (IllegalArgumentException exp) {
            JOptionPane.showMessageDialog(this, exp.getMessage(), "Validacion", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idCamioneroCamion == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione una asignacion de la tabla");
            return;
        }
        try {
            CamioneroCamion obj = leerFormulario();
            obj.setIdCamioneroCamion(idCamioneroCamion);
            dao.actualizar(obj);
            JOptionPane.showMessageDialog(this, "Datos actualizados correctamente");
            limpiar();
            cargarTabla();
        } catch (IllegalArgumentException exp) {
            JOptionPane.showMessageDialog(this, exp.getMessage(), "Validacion", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idCamioneroCamion == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione una asignacion de la tabla");
            return;
        }
        int resp = JOptionPane.showConfirmDialog(this, "Desea eliminar el registro seleccionado?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (resp != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            dao.eliminar(idCamioneroCamion);
            JOptionPane.showMessageDialog(this, "Registro eliminado correctamente");
            limpiar();
            cargarTabla();
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblCamioneroCamionMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCamioneroCamionMouseClicked
        int fila = tblCamioneroCamion.getSelectedRow();
        if (fila < 0) {
            return;
        }
        CamioneroCamion cc = lista.get(fila);
        idCamioneroCamion = cc.getIdCamioneroCamion();
        txtId.setText(String.valueOf(idCamioneroCamion));
        for (int i = 0; i < cmbCamionero.getItemCount(); i++) {
            if (cmbCamionero.getItemAt(i).getIdCamionero() == cc.getCamionero().getIdCamionero()) {
                cmbCamionero.setSelectedIndex(i);
                break;
            }
        }
        for (int i = 0; i < cmbCamion.getItemCount(); i++) {
            if (cmbCamion.getItemAt(i).getIdCamion() == cc.getCamion().getIdCamion()) {
                cmbCamion.setSelectedIndex(i);
                break;
            }
        }
    }//GEN-LAST:event_tblCamioneroCamionMouseClicked

    private void limpiar() {
        idCamioneroCamion = 0;
        txtId.setText("");
        cmbCamionero.setSelectedIndex(-1);
        cmbCamion.setSelectedIndex(-1);
        tblCamioneroCamion.clearSelection();
    }

    private CamioneroCamion leerFormulario() {
        CamioneroCamion cc = new CamioneroCamion();
        Validar.seleccion(cmbCamionero.getSelectedItem(), "un camionero");
        Validar.seleccion(cmbCamion.getSelectedItem(), "un camion");
        cc.setCamionero((Camionero) cmbCamionero.getSelectedItem());
        cc.setCamion((Camion) cmbCamion.getSelectedItem());
        return cc;
    }

    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblCamioneroCamion.getModel();
        modelo.setRowCount(0);
        try {
            lista = dao.listar();
            for (CamioneroCamion x : lista) {
                modelo.addRow(new Object[]{x.getIdCamioneroCamion(), x.getCamionero().toString(), x.getCamion().toString()});
            }
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void cargarCombos() {
        try {
            cmbCamionero.removeAllItems();
            for (Camionero c : new CamioneroDAO().listar()) {
                cmbCamionero.addItem(c);
            }
            cmbCamion.removeAllItems();
            for (Camion c : new CamionDAO().listar()) {
                cmbCamion.addItem(c);
            }
            cmbCamionero.setSelectedIndex(-1);
            cmbCamion.setSelectedIndex(-1);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

