    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            //leer y validar los datos del formulario
            Camion obj = leerFormulario();
            //almacenar los datos
            dao.insertar(obj);
            JOptionPane.showMessageDialog(this, "Datos almacenados correctamente");
            limpiar();
            cargarTabla();
        } catch (IllegalArgumentException exp) {
            JOptionPane.showMessageDialog(this, exp.getMessage(), "Validacion", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (idCamion == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un camion de la tabla");
            return;
        }
        try {
            Camion obj = leerFormulario();
            obj.setIdCamion(idCamion);
            dao.actualizar(obj);
            JOptionPane.showMessageDialog(this, "Datos actualizados correctamente");
            limpiar();
            cargarTabla();
        } catch (IllegalArgumentException exp) {
            JOptionPane.showMessageDialog(this, exp.getMessage(), "Validacion", JOptionPane.WARNING_MESSAGE);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (idCamion == 0) {
            JOptionPane.showMessageDialog(this, "Por favor seleccione un camion de la tabla");
            return;
        }
        int resp = JOptionPane.showConfirmDialog(this, "Desea eliminar el registro seleccionado?", "Confirmar", JOptionPane.YES_NO_OPTION);
        if (resp != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            dao.eliminar(idCamion);
            JOptionPane.showMessageDialog(this, "Registro eliminado correctamente");
            limpiar();
            cargarTabla();
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void tblCamionMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblCamionMouseClicked
        int fila = tblCamion.getSelectedRow();
        if (fila < 0) {
            return;
        }
        Camion c = lista.get(fila);
        idCamion = c.getIdCamion();
        txtId.setText(String.valueOf(idCamion));
        txtNoPlaca.setText(c.getNoPlaca());
        txtModelo.setText(c.getModelo());
        txtTipo.setText(c.getTipo());
        txtPotencia.setText(c.getPotencia().toString());
    }//GEN-LAST:event_tblCamionMouseClicked

    //limpia las cajas de texto
    private void limpiar() {
        idCamion = 0;
        txtId.setText("");
        txtNoPlaca.setText("");
        txtModelo.setText("");
        txtTipo.setText("");
        txtPotencia.setText("");
        tblCamion.clearSelection();
    }

    private Camion leerFormulario() {
        Camion c = new Camion();
        c.setNoPlaca(Validar.placa(txtNoPlaca.getText()));
        c.setModelo(Validar.texto(txtModelo.getText(), "Modelo", 50));
        c.setTipo(Validar.texto(txtTipo.getText(), "Tipo", 50));
        c.setPotencia(Validar.decimalPositivo(txtPotencia.getText(), "Potencia"));
        return c;
    }

    //llena la tabla
    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) tblCamion.getModel();
        modelo.setRowCount(0);
        try {
            lista = dao.listar();
            for (Camion x : lista) {
                modelo.addRow(new Object[]{x.getIdCamion(), x.getNoPlaca(), x.getModelo(), x.getTipo(), x.getPotencia()});
            }
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, Validar.mensajeSQL(exp), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

